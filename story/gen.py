    o=[f"# {c['title']}","",f"- 막: {c['act']}  ·  구현 상태: {c['status']}",f"- 장소/지형: {c['loc']}",f"- 목표: {c['goal']}",f"- 주요 사건: {c['events_desc']}",
       f"- 영입: {', '.join(c['recruits']) or '없음'}",f"- 보스: {c['boss'] or '없음'}",f"- 사이드 목표: {', '.join(c['side'])}","","## 오프닝",md_lines(c['pre']),"","## 전투 중 이벤트"]
    for t,ls in c['events'].items(): o+= [f"### {t}턴",md_lines(ls)]
    o+=["","## 보스 대사",md_lines(c['boss_lines'])]
    for k,ls in c.get('talk',{}).items(): o+=["",f"## 대화: {k.replace('|',' → ')}",md_lines(ls)]
    o+=["","## 엔딩",md_lines(c['post'])]
    if c.get('post_lost'): o+=["","## 엔딩 (노아 상실)",md_lines(c['post_lost'])]
    for k,ls in c.get('endings',{}).items(): o+=["",f"## 엔딩 분기: {k}",md_lines(ls)]
    o+=["","## 야영 대화",md_lines(c['camp'])]
    open(os.path.join(D, f"{cid}.md"),"w").write("\n".join(o)+"\n")

